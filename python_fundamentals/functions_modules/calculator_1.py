#!/usr/bin/env python3
"""Module that defines basic arithmetic functions."""


def add(a, b):
    """Add a and b."""
    return a + b


def sub(a, b):
    """Subtract b from a."""
    return a - b


def mul(a, b):
    """Multiply a by b."""
    return a * b


def div(a, b):
    """Divide a by b."""
    return a / b
